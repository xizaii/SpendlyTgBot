"""
Unit-тесты для классификатора категорий расходов.
"""

import pytest
from app.services.categorizer import detect_category


@pytest.mark.parametrize(
    "description, expected_category",
    [
        # Еда
        ("кофе", "Еда"),
        ("Капучино в кофейне", "Еда"),
        ("Обед в столовой", "Еда"),
        ("пицца пепперони", "Еда"),
        ("доставка продуктов самокат", "Еда"),
        ("шаурма на вокзале", "Еда"),
        ("суши и роллы", "Еда"),
        ("Пятерочка продукты", "Еда"),
        
        # Транспорт
        ("такси до аэропорта", "Транспорт"),
        ("поездка на метро", "Транспорт"),
        ("бензин на лукойле", "Транспорт"),
        ("каршеринг делимобиль", "Транспорт"),
        ("автобус номер 5", "Транспорт"),
        ("шиномонтаж", "Транспорт"),
        
        # Жильё
        ("аренда квартиры", "Жильё"),
        ("оплата жкх", "Жильё"),
        ("счет за свет и воду", "Жильё"),
        ("интернет ростелеком", "Жильё"),
        ("квартплата за ноябрь", "Жильё"),
        
        # Развлечения
        ("билеты в кино", "Развлечения"),
        ("поход в театр", "Развлечения"),
        ("посиделки в баре", "Развлечения"),
        ("подписка netflix", "Развлечения"),
        ("яндекс плюс подписка", "Развлечения"),
        ("игра в steam", "Развлечения"),
        
        # Здоровье
        ("покупка в аптеке", "Здоровье"),
        ("таблетки от головы", "Здоровье"),
        ("прием у врача", "Здоровье"),
        ("лечение зуба стоматолог", "Здоровье"),
        ("абонемент в спортзал", "Здоровье"),
        
        # Прочее (неизвестные слова)
        ("купил ноутбук", "Прочее"),
        ("подарок для друга", "Прочее"),
        ("ручка и блокнот", "Прочее"),
        ("", "Прочее"),
    ]
)
def test_detect_category(description: str, expected_category: str):
    """Проверка правильного сопоставления текста с категорией."""
    assert detect_category(description) == expected_category
