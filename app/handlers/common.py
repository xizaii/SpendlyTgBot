"""
Обработчики общих команд бота: /start и /help.
"""

from aiogram import Router
from aiogram.filters import Command, CommandStart
from aiogram.types import Message

router = Router(name="common")


@router.message(CommandStart())
async def cmd_start(message: Message) -> None:
    """
    Обработчик команды /start.
    Приветствует пользователя и кратко объясняет, как пользоваться ботом.
    """
    first_name = message.from_user.first_name if message.from_user else "друг"
    welcome_text = (
        f"👋 Привет, <b>{first_name}</b>!\n\n"
        "Я бот для быстрого и простого учёта твоих личных расходов.\n\n"
        "<b>Как записать трату?</b>\n"
        "Просто напиши мне сообщение с описанием и суммой (в любом порядке):\n"
        "• <code>кофе 150</code>\n"
        "• <code>такси 420.50</code>\n"
        "• <code>3000 аренда</code>\n\n"
        "Я сам определю категорию (Еда, Транспорт, Жильё и др.) и сохраню запись.\n\n"
        "<b>Основные команды:</b>\n"
        "/today — расходы за сегодня\n"
        "/week — расходы за последние 7 дней\n"
        "/month — расходы за последние 30 дней\n"
        "/last — показать последние 10 трат\n"
        "/undo — удалить последнюю записанную трату\n"
        "/help — подробная справка"
    )
    await message.answer(welcome_text)


@router.message(Command("help"))
async def cmd_help(message: Message) -> None:
    """
    Обработчик команды /help.
    Показывает полный список доступных команд и правила ввода.
    """
    help_text = (
        "<b>📖 Справка по использованию бота</b>\n\n"
        "<b>1. Добавление трат:</b>\n"
        "Отправьте текстовое сообщение с суммой и описанием:\n"
        "• <code>обед 350</code> — сумма в конце\n"
        "• <code>450.50 такси</code> — сумма в начале\n"
        "• <code>продукты 1200,50</code> — можно использовать запятую или точку\n\n"
        "<b>2. Категории трат:</b>\n"
        "Определяются автоматически по ключевым словам:\n"
        "• 🍔 <b>Еда</b> (кофе, обед, продукты, пицца...)\n"
        "• 🚕 <b>Транспорт</b> (такси, метро, бензин, автобус...)\n"
        "• 🏠 <b>Жильё</b> (аренда, жкх, интернет, свет...)\n"
        "• 🎬 <b>Развлечения</b> (кино, игры, бар, подписка...)\n"
        "• 💊 <b>Здоровье</b> (аптека, врач, таблетки, спортзал...)\n"
        "• 📦 <b>Прочее</b> (всё, что не подошло в другие категории)\n\n"
        "<b>3. Отчёты и статистика:</b>\n"
        "/today — сводка расходов за сегодняшний день\n"
        "/week — сводка расходов за 7 дней\n"
        "/month — сводка расходов за 30 дней\n"
        "/last — список последних 10 записей\n\n"
        "<b>4. Исправление ошибок:</b>\n"
        "/undo — если ошиблись, удаляет вашу самую последнюю трату."
    )
    await message.answer(help_text)
